"""Pydantic v2 schemas for the AMANA SHIELD Risk Fusion Engine.

Maintains strict separation between:
1. message_risk
2. url_risk
3. claim_verification_status

Guarantees predictable, auditable verdicts and clean localization support (English & Hausa).
"""

from __future__ import annotations

import uuid
from datetime import datetime
from enum import StrEnum
from typing import Literal, Optional

from pydantic import BaseModel, ConfigDict, Field

from app.models.entities import (
    ClaimVerificationStatus,
    ConfidenceLevel,
    InternalStatus,
    MessageRisk,
    PublicVerdict,
    UrlRisk,
)


class SupportedLanguage(StrEnum):
    """Supported explanation languages."""

    ENGLISH = "en"
    HAUSA = "ha"


class LocalizedExplanation(BaseModel):
    """Channel-ready explanation and recommended action localized for users."""

    model_config = ConfigDict(extra="forbid")

    language: SupportedLanguage
    verdict_badge: str
    summary: str
    reasons: list[str] = Field(default_factory=list)
    recommended_action: str
    evidence_points: list[str] = Field(default_factory=list)
    uncertainty_note: Optional[str] = None


class RiskFusionEvaluation(BaseModel):
    """Complete, transparent assessment bundle generated by the Risk Fusion Engine."""

    model_config = ConfigDict(extra="forbid")

    submission_id: Optional[uuid.UUID] = None

    # Three independent pillar assessments (strictly uncollapsed)
    message_risk: MessageRisk
    url_risk: UrlRisk
    claim_verification_status: ClaimVerificationStatus

    # Public verdict and internal review status
    verdict: PublicVerdict
    review_status: InternalStatus = InternalStatus.UNDER_REVIEW

    # Traceability & rules
    triggered_rules: list[str] = Field(default_factory=list)
    reasons: list[str] = Field(default_factory=list)
    evidence: list[str] = Field(default_factory=list)
    confidence: ConfidenceLevel = ConfidenceLevel.HIGH
    uncertainty_indicators: list[str] = Field(default_factory=list)

    # Localized public outputs
    primary_explanation: LocalizedExplanation
    available_localizations: dict[str, LocalizedExplanation] = Field(default_factory=dict)
    recommended_action: str

    assessment_timestamp: datetime
    is_degraded_mode: bool = False
